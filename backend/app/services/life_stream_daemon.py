def _sqlite_query(path: str, sql: str, params: tuple = ()) -> list[tuple]:
    uri = f"file:{os.path.abspath(path)}?mode=ro"
    last: Exception | None = None
    for attempt in range(3):
        try:
            conn = sqlite3.connect(uri, uri=True, timeout=5.0)
            try:
                cursor = conn.cursor()
                cursor.execute(sql, params)
                return list(cursor.fetchall())
            finally:
                conn.close()
        except sqlite3.OperationalError as exc:
            last = exc
            # Locked/busy when Mail/WhatsApp/Messages vacuum — back off and retry.
            if "locked" not in str(exc).lower() and "busy" not in str(exc).lower():
                raise
            time.sleep(0.25 * (attempt + 1))
        except Exception:
            raise
    if last is not None:
        raise last
    return []


def _sqlite_scalar(path: str, sql: str, params: tuple = ()) -> Any:
    rows = _sqlite_query(path, sql, params)
    if not rows:
        return None
    return rows[0][0]


def _is_whatsapp_system_body(body: str) -> bool:
    """True for non-chat ZTEXT: bare JIDs, group invites, media refs."""
    text = (body or "").strip()
    if not text:
        return True
    if len(text) > 120:
        return False
    lowered = text.lower()
    # Bare JID like 107065062195290@lid or 120363...@g.us
    if "@lid" in lowered or "@g.us" in lowered or "@c.us" in lowered:
        compact = "".join(ch for ch in lowered if ch.isalnum() or ch in {"@", ".", "-", "_"})
        if len(compact) >= len(text.strip()) - 2:
            return True
    return False


def _is_whatsapp_broadcast_channel(sess_type: object, *jids: object) -> bool:
    """Status, Channels/newsletters, and broadcast lists are not chats."""
    try:
        if int(sess_type or 0) in {3, 5}:
            return True
    except (TypeError, ValueError):
        pass
    blob = " ".join(str(v or "") for v in jids).lower()
    return any(tag in blob for tag in ("@status", "@newsletter", "@broadcast"))


_PHONE_HANDLE_STRIP = dict.fromkeys(
    map(ord, "\u202a\u202b\u202c\u202d\u202e\u200e\u200f\xa0"), None
)


def _is_unnamed_phone_handle(handle: str) -> bool:
    """True for a digits-only WhatsApp partner (business ads, unsaved LID)."""
    raw = (handle or "").translate(_PHONE_HANDLE_STRIP).strip()
    if not raw:
        return False
    letters = re.sub(r"[^A-Za-z]", "", raw)
    digits = re.sub(r"\D", "", raw)
    return len(letters) < 2 and len(digits) >= 8


_TXN_SENDER_RE = re.compile(
    # Indian DLT headers survive mixed-case in Messages (ViCARE-S, ECIsms-G).
    # Two shapes: operator-PE (JD-ANKIAB) and PE-type (INVCPP-T, ViCARE-S).
    # Cap the suffix at 2 so hyphenated names (Mary-Jane) stay people.
    r"^[A-Za-z]{2}-[A-Za-z0-9]{5,6}$"
    r"|^[A-Za-z0-9]{2,6}-[A-Za-z0-9]{1,2}$"
    r"|^\d{3,6}$"  # numeric shortcodes: 56767, 121
    r"|^[A-Z0-9]{2,11}$",  # bare service headers: HDFCBK, INVCPP (all-caps, no spaces)
)
_TXN_BODY_RE = re.compile(
    r"\botp\b|one[\s-]?time (pass|password)|verification code|"
    r"\bcode\b.{0,12}\b(is|:)\b.{0,8}\d{4,8}|"
    r"\b(debited|credited)\b|a/c\b.{0,16}\b(x|xx|\*)|upi.{0,24}(ref|txn|transaction)|"
    r"\b(neft|imps|rtgs)\b|txn id|transaction id|"
    r"\b(account|card).{0,32}\b(rs\.?|inr|₹)\s?[\d,]+",
    re.IGNORECASE,
)


def _is_transactional_sms(body: str, handle: str) -> bool:
    """True for OTP / bank / service SMS that should not top a digest.

    iMessage handles are phone numbers, emails, or service headers — never
    bare first names. Service headers and shortcodes are transactional on
    sight; anyone else needs a strong OTP/bank signal in the body.
    """
    sender = (handle or "").strip()
    text = (body or "").strip()
    if not sender and not text:
        return False
    if sender and _TXN_SENDER_RE.match(sender):
        return True
    lowered_handle = sender.lower()
    if "@botplatform" in lowered_handle or lowered_handle.endswith(".jio"):
        return True
    if "evie-pair." in text.lower():
        return True
    if re.search(r"dear customer.{0,80}missed call", text, re.I):
        return True
    compact = text.strip()
    if compact in {"", "\ufffd", "￾"} or (
        len(compact) <= 2 and not any(ch.isalnum() for ch in compact)
    ):
        return True
    return bool(text) and bool(_TXN_BODY_RE.search(text))


_ROLE_LOCAL_RE = re.compile(
    r"^(no-?reply|no_reply|donotreply|do-not-reply|"
    r"mailer-daemon|mailerdaemon|postmaster|abuse|"
    r"notifications?|newsletters?|updates|marketing|support|billing|"
    r"news|hello|hi|hey|team|info|bounces?|unsubscribe)$",
    re.IGNORECASE,
)
_MAIL_ROLL_LABEL_RE = re.compile(
    r"^(mail|email|updates|news|smtp|bounce|bounces|m|em|send)$",
    re.IGNORECASE,
)
_FROM_BRAND_RE = re.compile(
    r"^[A-Za-z][\w.'-]+ from [A-Z]",
)
_FROM_ANGLE_RE = re.compile(r"^(?P<name>.*?)\s*<(?P<addr>[^>]+)>\s*$")


def _mail_from_parts(sender: str) -> tuple[str, str, str]:
    """Display name, local-part, domain — empty strings when missing."""
    text = " ".join(str(sender or "").split()).strip()
    if not text:
        return "", "", ""
    angled = _FROM_ANGLE_RE.match(text)
    if angled:
        display = (angled.group("name") or "").strip().strip('"')
        addr = (angled.group("addr") or "").strip()
    elif "@" in text and "<" not in text:
        display, addr = "", text
    else:
        return text, "", ""
    local, _, domain = addr.partition("@")
    return display, local.strip(), domain.strip().lower()


def _is_bulk_mail(sender: str, subject: str = "") -> bool:
    """True for one-way envelopes: role mailboxes, mail-roll hosts, brand From.

    Structural, not a brand list. `notifications@any.domain` is bulk;
    `Ada <ada@example.com>` is not. Subject is unused — topic words are
    not a reliable bulk signal.
    """
    del subject
    display, local, domain = _mail_from_parts(sender)
    if local and _ROLE_LOCAL_RE.match(local):
        return True
    label = domain.split(".", 1)[0] if domain else ""
    if label and _MAIL_ROLL_LABEL_RE.match(label):
        return True
    if display and _FROM_BRAND_RE.match(display):
        return True
    return False


def _mail_sender_in_contacts(sender: str, contacts: list[dict[str, Any]]) -> bool:
    """True when the envelope matches a stored person (email or full name)."""
    display, local, domain = _mail_from_parts(sender)
    addr = f"{local}@{domain}".lower() if local and domain else ""
    hay = f"{display} {addr}".strip().lower()
    if not hay:
        return False
    for row in contacts:
        if not isinstance(row, dict):
            continue
        email = str(row.get("email") or "").strip().lower()
        if email and email in hay:
            return True
        extra = row.get("email_addresses") or row.get("emails") or []
        if isinstance(extra, list):
            for item in extra:
                val = (
                    str(item.get("email") or "")
                    if isinstance(item, dict)
                    else str(item or "")
                ).strip().lower()
                if val and val in hay:
                    return True
        name = str(row.get("name") or row.get("full_name") or "").strip().lower()
        # Full name only — a lone first name collides with brands.
        if name and " " in name and name in hay:
            return True
    return False


def _group_per_person(hits: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Latest hit per handle, newest first. One loud thread can't flood a digest."""
    seen: set[str] = set()
    grouped: list[dict[str, Any]] = []
    for hit in hits:
        key = str(hit.get("handle") or "").strip().lower()
        if not key:
            key = str(hit.get("text") or "")[:48].lower()
        if key in seen:
            continue
        seen.add(key)
        grouped.append(hit)
    return grouped


def _filter_peek(rows: list[dict[str, Any]], tokens: list[str], limit: int) -> list[dict[str, Any]]:
    cap = max(1, min(int(limit or 8), 8))
    # The blob is lowercased — tokens must be too, or capitalized person
    # names ("Mansi") never match. Central fix for every peek caller.
    normalized = [
        str(token or "").strip().lower() for token in (tokens or []) if str(token or "").strip()
    ]
    if not normalized:
        return rows[:cap]
    scored: list[tuple[float, dict[str, Any]]] = []
    for row in rows:
        blob = " ".join(
            str(row.get(key) or "")
            for key in ("text", "gist", "subject", "sender")
        ).lower()
        hits = sum(1 for token in normalized if token and token in blob)
        if hits <= 0:
            continue
        item = dict(row)
        item["score"] = round(hits / len(normalized), 4)
        scored.append((hits / len(normalized), item))
    scored.sort(key=lambda item: item[0], reverse=True)
    return [item for _, item in scored[:cap]]


def health_snapshot_event_create(row: Any) -> EventCreate | None:
    """Compact health envelope. Metrics only; never dumped into chat."""
    if isinstance(row, dict):
        sid = str(row.get("id") or row.get("occurred_at") or "")
        readiness = row.get("readiness")
        metrics = row.get("metrics") if isinstance(row.get("metrics"), dict) else {}
        occurred = row.get("occurred_at")
    else:
        sid = str(getattr(row, "id", "") or "")
        readiness = getattr(row, "readiness", None)
        raw_metrics = getattr(row, "metrics", None)
        metrics = raw_metrics if isinstance(raw_metrics, dict) else {}
        occurred = getattr(row, "occurred_at", None)
    if not sid:
        return None
    bits = []
    if readiness is not None:
        bits.append(f"readiness {readiness}")
    compact: dict[str, Any] = {}
    for key in _HEALTH_METRIC_KEYS:
        value = metrics.get(key)
        if isinstance(value, (int, float)):
            compact[key] = value
            bits.append(f"{key} {value}")
    text = "Health: " + ", ".join(bits) if bits else "Health snapshot"
    return EventCreate(
        event_type="health.snapshot.recorded",
        source="health",
        content={"text": text, "readiness": readiness, "metrics": compact},
        occurred_at=occurred if occurred else None,
        privacy_level="sensitive",
        metadata={"source": "health_snapshot", "channel": "health", "snapshot_id": sid},
    )


class LifeStreamDaemon:
    """Headless sensory daemon for continuous background data observation."""

    def __init__(
        self,
        *,
        chat_db_path: str | None = None,
        last_message_rowid: int = 0,
        whatsapp_db_path: str | None = None,
        call_db_path: str | None = None,
        photos_db_path: str | None = None,
        mail_index_path: str | None = None,
    ) -> None:
        default_chat = os.path.expanduser("~/Library/Messages/chat.db")
        default_whatsapp = os.path.expanduser(
            "~/Library/Group Containers/group.net.whatsapp.WhatsApp.shared/ChatStorage.sqlite"
        )
        default_calls = os.path.expanduser(
            "~/Library/Application Support/CallHistoryDB/CallHistory.storedata"
        )
        default_photos = os.path.expanduser(
            "~/Pictures/Photos Library.photoslibrary/database/Photos.sqlite"
        )
        self.chat_db_path = default_chat if chat_db_path is None else chat_db_path
        # Isolated tests pass a temp chat.db. Do not also open the owner's
        # WhatsApp / CallHistory / Photos libraries unless those paths are set.
        use_real_hub = chat_db_path is None
        self.whatsapp_db_path = (
            default_whatsapp
            if whatsapp_db_path is None and use_real_hub
            else (whatsapp_db_path or "")
        )
        self.call_db_path = (
            default_calls
            if call_db_path is None and use_real_hub
            else (call_db_path or "")
        )
        self.photos_db_path = (
            default_photos
            if photos_db_path is None and use_real_hub
            else (photos_db_path or "")
        )
        self.mail_index_path = (
            find_mail_envelope_index()
            if mail_index_path is None and use_real_hub
            else (mail_index_path or "")
        )
        # Auto-resolved only: may be re-resolved when unreadable (Mail.app
        # upgrades move V10 -> V11; rebuilds briefly remove the file).
        # Explicitly-passed paths (tests) are never swapped for owner data.
        self._mail_index_auto = mail_index_path is None and use_real_hub
        self.last_message_rowid = last_message_rowid
        self.last_whatsapp_pk = 0
        self.last_call_pk = 0
        self.last_photo_pk = 0
        self._known_contact_ids: set[str] = set()
        self._contact_fps: dict[str, str] = {}
        self._mail_fps: dict[str, str] = {}
        self._calendar_fps: dict[str, str] = {}
        self._health_fps: dict[str, str] = {}
        self._last_account_pull: float = 0.0
        self._cursor_path: Path | None = None
        self._bootstrapped: set[str] = set()
        self._cached_contacts: list[dict[str, Any]] = []

    def remember_contacts(self, contacts: list[dict[str, Any]]) -> None:
        """Keep a short ask-time copy of the last helper address-book pull."""
        self._cached_contacts = [row for row in contacts if isinstance(row, dict)][:500]

    def is_chat_db_accessible(self) -> bool:
        """Return True if chat.db exists and is readable (Full Disk Access granted)."""
        return _sqlite_readable(self.chat_db_path)

    def refresh_mail_index_path(self) -> str:
        """Re-resolve the Envelope Index when the held path went stale.

        Never raises. Only applies to auto-resolved hubs; explicit test
        paths are left untouched so tests can't leak into owner Mail.
        """
        if not getattr(self, "_mail_index_auto", False):
            return self.mail_index_path
        if _sqlite_readable(self.mail_index_path):
            return self.mail_index_path
        try:
            found = find_mail_envelope_index()
        except Exception:
            return self.mail_index_path
        if found:
            self.mail_index_path = found
        return self.mail_index_path

    def _catchup_pk(self, attr: str, path: str, table: str, column: str = "Z_PK") -> int:
        """On first sight of a large DB, start near the live tail instead of year one."""
        current = int(getattr(self, attr) or 0)
        if current > 0 or attr in self._bootstrapped:
            return current
        self._bootstrapped.add(attr)
        if not _sqlite_readable(path):
            return 0
        try:
            max_pk = _sqlite_scalar(path, f"SELECT MAX({column}) FROM {table}")
        except Exception:  # noqa: BLE001 - missing table is a skip, not a crash
            return 0
        if not isinstance(max_pk, (int, float)) or max_pk is None:
            return 0
        start = max(0, int(max_pk) - _LIVE_CATCHUP)
        setattr(self, attr, start)
        return start

    async def _safe_sync(
        self,
        name: str,
        coro,
        session: AsyncSession | None = None,
    ) -> list[Any]:
        try:
            return await coro
        except Exception as exc:  # noqa: BLE001 - one stream must not skip the others
            logger.warning("life stream %s skipped: %s", name, type(exc).__name__)
            if session is not None:
                with contextlib.suppress(Exception):
                    await session.rollback()
            return []

    async def sync_imessage(
        self,
        session: AsyncSession,
        *,
        limit: int = 50,
    ) -> list[Any]:
        """Poll chat.db for messages newer than last_message_rowid and ingest them."""
        if not self.is_chat_db_accessible():
            logger.debug(
                "chat.db not accessible at '%s' (degraded or FDA missing)",
                self.chat_db_path,
            )
            return []

        events = []
        event_service = EventService(session, actor="life_stream_daemon")

        try:
            rows = _sqlite_query(
                self.chat_db_path,
                """
                    SELECT message.ROWID, message.date, message.text, handle.id, message.is_from_me
                    FROM message
                    LEFT JOIN handle ON message.handle_id = handle.ROWID
                    WHERE message.ROWID > ?
                    ORDER BY message.ROWID ASC
                    LIMIT ?
                """,
                (self.last_message_rowid, max(1, limit)),
            )
        except Exception as exc:
            logger.warning("Failed reading chat.db: %s", exc)
            return []

        # Cursor advances only after a successful commit. Advancing per-row
        # loses messages when commit fails (cursor ahead of stored events).
        seen_max = self.last_message_rowid
        for rowid, raw_date, raw_text, handle, is_from_me in rows:
            text = (raw_text or "").strip()
            if rowid > seen_max:
                seen_max = rowid
            if not text:
                continue

            occurred_at = _apple_timestamp_to_datetime(raw_date)
            sender_or_target = str(handle or "unknown").strip()
            from_me = bool(is_from_me)

            event_type = (
                "message.imessage.sent" if from_me else "message.imessage.received"
            )
            event_create = EventCreate(
                event_type=event_type,
                source="imessage",
                content={
                    "text": text,
                    "handle": sender_or_target,
                    "is_from_me": from_me,
                    "rowid": rowid,
                },
                occurred_at=occurred_at,
                privacy_level="sensitive",
                metadata={"source_rowid": rowid, "channel": "messages"},
            )

            created_event = await event_service.create(event_create)
            events.append(created_event)

        if events:
            await session.commit()
            self.last_message_rowid = seen_max
            logger.info("Ingested %d new iMessage events (latest rowid: %d)", len(events), self.last_message_rowid)
        elif seen_max > self.last_message_rowid:
            # All rows skipped (empty bodies): nothing written, safe to advance.
            self.last_message_rowid = seen_max

        return events

