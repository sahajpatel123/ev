def _sqlite_readable(path: str | None) -> bool:
    return bool(path) and os.path.isfile(path) and os.access(path, os.R_OK)


def find_mail_envelope_index() -> str:
    """Newest Apple Mail Envelope Index on this Mac, or empty."""
    root = os.path.expanduser("~/Library/Mail")
    if not os.path.isdir(root):
        return ""
    versions: list[tuple[int, str]] = []
    try:
        names = os.listdir(root)
    except OSError:
        return ""
    for name in names:
        if not name.startswith("V"):
            continue
        try:
            versions.append((int(name[1:]), name))
        except ValueError:
            continue
    versions.sort(reverse=True)
    for _, name in versions:
        path = os.path.join(root, name, "MailData", "Envelope Index")
        if _sqlite_readable(path):
            return path
    return ""


def _mac_app_running(*names: str) -> bool:
    """True when any of the app process names is running. No windows touched."""
    import subprocess

    for name in names:
        try:
            proc = subprocess.run(
                ["pgrep", "-x", name],
                capture_output=True,
                timeout=3,
            )
            if proc.returncode == 0 and (proc.stdout or b"").strip():
                return True
        except Exception:
            continue
    return False


def _db_mtime_age(path: str | None) -> float | None:
    """Seconds since the sqlite file changed. None when missing.

    Apple databases run in WAL mode: new messages land in -wal/-shm while
    the main file sits untouched for hours. Newest of the three is the truth.
    """
    if not path or not os.path.isfile(path):
        return None
    newest: float | None = None
    for candidate in (path, f"{path}-wal", f"{path}-shm"):
        try:
            if not os.path.isfile(candidate):
                continue
            mtime = os.path.getmtime(candidate)
            newest = mtime if newest is None else max(newest, mtime)
        except OSError:
            continue
    if newest is None:
        return None
    return max(0.0, time.time() - newest)


def ensure_background_sync(*, stale_after_seconds: float = 1800.0) -> dict[str, Any]:
    """Launch WhatsApp/Mail hidden when they are not running.

    Hidden background launch (``open -jg``): no windows, no focus steal.
    A quit app cannot ingest new messages, so we relaunch even if the
    sqlite copy looks recent. ``stale_after_seconds`` is unused for the
    launch gate (kept so callers stay source-compatible).
    """
    import subprocess

    # Call-site compatibility: a quit app is always stale for incoming mail/chats.
    _ = stale_after_seconds
    outcome: dict[str, Any] = {"checked": [], "launched": []}
    if not life_stream_should_run():
        return outcome
    try:
        from app.services.life_stream_daemon import get_life_stream_daemon

        daemon = get_life_stream_daemon()
    except Exception:
        return outcome
    with contextlib.suppress(Exception):
        daemon.refresh_mail_index_path()
    targets = [
        {
            "key": "whatsapp",
            "path": getattr(daemon, "whatsapp_db_path", ""),
            "procs": ("WhatsApp",),
            "app": "/Applications/WhatsApp.app",
        },
        {
            "key": "mail",
            "path": getattr(daemon, "mail_index_path", ""),
            "procs": ("Mail",),
            "app": "/System/Applications/Mail.app",
        },
    ]
    now = time.time()
    for target in targets:
        key = str(target["key"])
        outcome["checked"].append(key)
        if _mac_app_running(*target["procs"]):  # type: ignore[arg-type]
            continue
        last = _last_bg_launch.get(key, 0.0)
        if now - last < _BG_LAUNCH_COOLDOWN_S:
            continue
        app_path = str(target["app"])
        if not os.path.isdir(app_path):
            continue
        try:
            subprocess.run(
                ["open", "-jg", app_path],
                capture_output=True,
                timeout=10,
            )
            _last_bg_launch[key] = now
            outcome["launched"].append(key)
            age = _db_mtime_age(str(target["path"] or ""))
            logger.info(
                "Background sync: launched %s hidden (app was not running, db age %s)",
                key,
                f"{age:.0f}s" if age is not None else "unknown",
            )
        except Exception:
            continue
    return outcome


