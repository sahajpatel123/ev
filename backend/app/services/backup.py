"""Encrypted backup, verification, and restore for the EV data store.

Backups are single encrypted JSON files with an ``ev.backup.v1`` envelope:

- The plaintext bundle contains the immutable event log, attachment metadata,
  registered devices, the access log, and the derived-memory snapshot (so a
  restore drill can verify counts and content equivalence).
- The bundle is authenticated-encrypted with Fernet using a key derived with
  scrypt from a **user-held passphrase** (the same KDF used for voiceprints).
- A SHA-256 of the canonical plaintext is stored in the envelope, so tampering
  is detected before any restore can proceed.
- Restore is event-sourced: raw events are re-inserted (deduplicated by content
  hash) and every derived memory/entity/relationship/conflict is regenerated by
  ``rebuild_derived_state``, matching the import path.

The backup passphrase is deliberately separate from ``EV_MASTER_KEY``: a leaked
database or master key does not decrypt old backups, and vice versa.
"""

