"""WP13 test-debt triage: compare a branch run against the pre-fabric baseline.

The baseline is a *full* run of ``pre-fabric-baseline`` in a detached worktree,
stored as node-id sets (``--baseline-json``). This script:

1. reads both node-id sets,
2. classifies every branch failure as **regression** (fails here, passed at
   baseline), **pre-existing** (fails at both), **fixed** (failed at baseline,
   passes here) or **new** (not present in the baseline run at all),
3. applies the triage table in ``docs/TEST_DEBT_TRIAGE.json`` (environment /
   stale test / real bug) so the same failure is never re-diagnosed, and
4. writes ``docs/TEST_DEBT.md``.

Exit code is 1 if any regression is unexplained — that is the WP13 gate.

Usage::

    python -m app.scripts.test_debt --baseline-json /tmp/ev-baseline/nodeids.json \
        --branch-junit /tmp/ev-branch/junit.xml --write
"""
from __future__ import annotations

import argparse
import json
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DOC = ROOT / "docs" / "TEST_DEBT.md"
TRIAGE = ROOT / "docs" / "TEST_DEBT_TRIAGE.json"


def nodeids_from_junit(path: Path) -> dict[str, list[str]]:
    root = ET.parse(path).getroot()
    out: dict[str, list[str]] = {"passed": [], "failed": [], "errored": [], "skipped": []}
    for tc in root.iter("testcase"):
        cls = (tc.get("classname") or "").split(".")
        nid = "/".join(cls) + ".py::" + (tc.get("name") or "")
        kinds = {c.tag for c in tc}
        if "failure" in kinds:
            out["failed"].append(nid)
        elif "error" in kinds:
            out["errored"].append(nid)
        elif "skipped" in kinds:
            out["skipped"].append(nid)
        else:
            out["passed"].append(nid)
    for k in out:
        out[k].sort()
    return out


def load_triage() -> dict:
    if TRIAGE.exists():
        try:
            return json.loads(TRIAGE.read_text())
        except ValueError:
            return {}
    return {}


def classify(rule: dict) -> str:
    kind = rule.get("kind", "unexplained")
    return {"env": "environment-dependent", "stale": "stale test",
            "bug": "real bug", "fixed": "fixed"}.get(kind, "unexplained")


def build(bs: dict[str, list[str]], br: dict[str, list[str]], triage: dict) -> dict:
    b_fail = set(bs["failed"]) | set(bs["errored"])
    r_fail = set(br["failed"]) | set(br["errored"])
    b_pass = set(bs["passed"])
    regressions = sorted(r_fail - b_fail)
    # A regression only counts when the baseline actually PASSED it; a test that
    # simply did not exist at baseline cannot regress.
    undiscovered = sorted(n for n in regressions if n not in b_pass)
    fixed = sorted(b_fail - r_fail)
    return {
        "baseline": {k: len(v) for k, v in bs.items()},
        "branch": {k: len(v) for k, v in br.items()},
        "regressions": regressions,
        "regressions_unexplained": [n for n in regressions
                                    if n not in triage],
        "new_at_branch": [n for n in r_fail if n not in b_fail and n in undiscovered],
        "pre_existing": sorted(r_fail & b_fail),
        "fixed": fixed,
    }


def render(result: dict, triage: dict) -> str:
    b, r = result["baseline"], result["branch"]
    unf = result["regressions_unexplained"]
    lines = [
        "# Test debt (evie-fabric final run)",
        "",
        "Generated by `python -m app.scripts.test_debt`. The baseline is a full",
        "run of the `pre-fabric-baseline` tag in a detached worktree; every number",
        "below is a node-id set difference, not a sample.",
        "",
        "## Counts",
        "",
        "| | passed | failed | errored | skipped |",
        "| --- | --- | --- | --- | --- |",
        f"| baseline `pre-fabric-baseline` | {b['passed']} | {b['failed']} | "
        f"{b['errored']} | {b['skipped']} |",
        f"| branch `evie-fabric` | {r['passed']} | {r['failed']} | "
        f"{r['errored']} | {r['skipped']} |",
        "",
        "## Set differences",
        "",
        f"- **regressions** (fail here, passed at baseline): {len(result['regressions'])}",
        f"- of which **unexplained**: {len(unf)}",
        f"- **pre-existing** (fail at both): {len(result['pre_existing'])}",
        f"- **fixed** (failed at baseline, pass here): {len(result['fixed'])}",
        "",
    ]
    if unf:
        lines += ["## Unexplained regressions — WP13 gate FAILS while non-empty", "", "```text"]
        lines += unf[:200]
        lines += ["```", ""]
    if result["fixed"]:
        lines += ["## Fixed since baseline", "", "```text"]
        lines += result["fixed"][:400]
        lines += ["```", ""]
    lines += ["## Triage of pre-existing failures", "",
              "| test | cause | note |", "| --- | --- | --- |"]
    for nid in sorted(result["pre_existing"]):
        rule = triage.get(nid)
        if rule:
            lines.append(f"| `{nid}` | {classify(rule)} | {rule.get('note','')} |")
        else:
            lines.append(f"| `{nid}` | unexplained | not yet triaged |")
    if result["pre_existing"]:
        lines += ["", "## Names of pre-existing failures", "", "```text"]
        lines += result["pre_existing"][:600]
        lines += ["```", ""]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="test-debt")
    ap.add_argument("--baseline-json", required=True)
    ap.add_argument("--branch-junit", required=True)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--json-out", default="")
    args = ap.parse_args(argv)

    bs = json.loads(Path(args.baseline_json).read_text())
    br = nodeids_from_junit(Path(args.branch_junit))
    triage = load_triage()
    result = build(bs, br, triage)
    print(f"regressions={len(result['regressions'])} "
          f"unexplained={len(result['regressions_unexplained'])} "
          f"pre-existing={len(result['pre_existing'])} "
          f"fixed={len(result['fixed'])}")
    if args.write:
        DOC.write_text(render(result, triage))
        print(f"wrote {DOC}")
    if args.json_out:
        Path(args.json_out).write_text(json.dumps(result, indent=1))
    return 1 if result["regressions_unexplained"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
